#!/usr/bin/env python3
"""gen_ocr_parity.py -- the parity fixtures of ocr_model_parity_narrated.ring: a fixed input per PP-OCR
model and onnxruntime's output on it, as STZT tensor files the engine's ocr_graph.zig reads.

    <docling venv>/python -I -X utf8 gen_ocr_parity.py          (run from base/test/ocr/tools)

The inputs come from the page-1 render of golden_v36/z09 (../_data/z09_p1_150dpi.png): the detector sees a
region resized to 256x192, the recogniser a drawn text line ("Plaine 2026", Arial) at 48x128, the classifier the same line
at 48x192 -- PP-OCR's own normalisation (BGR; ImageNet mean/std for the detector, (x-0.5)/0.5 for the others), batch 1. The sizes are chosen so the
expected files stay under a megabyte each; parity does not need a full page. The models are the ones the
Docling venv's rapidocr ships (PP-OCRv6 det/rec small, ch_ppocr_mobile_v2.0 cls), and the outputs are
onnxruntime's, written once and never regenerated by the engine side.

STZT file: "STZT", u32 rank, 4 x i64 dims (ONNX order, 1 where unused), f32 data row-major.
"""
import os
import struct
import sys

import numpy as np
import onnxruntime as ort
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "_data")
OUT = os.path.join(DATA, "parity")
MODELS = os.path.join(sys.prefix, "Lib", "site-packages", "rapidocr", "models")

MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def write(path, arr):
    arr = np.ascontiguousarray(arr, dtype=np.float32)
    dims = list(arr.shape) + [1] * (4 - arr.ndim)
    with open(path, "wb") as f:
        f.write(b"STZT" + struct.pack("<I", arr.ndim) + struct.pack("<4q", *dims))
        f.write(arr.astype("<f4").tobytes())


def tensor(img, w, h, imagenet):
    # PaddleOCR reads with cv2, so the channels are BGR; the detector normalises with the ImageNet mean and
    # std, the recogniser and the classifier with (x - 0.5) / 0.5
    im = img.convert("RGB").resize((w, h), Image.BILINEAR)
    a = np.asarray(im, dtype=np.float32)[:, :, ::-1] / 255.0
    a = (a - MEAN) / STD if imagenet else (a - 0.5) / 0.5
    return np.ascontiguousarray(a.transpose(2, 0, 1)[None], dtype=np.float32)


def run(model, x):
    s = ort.InferenceSession(os.path.join(MODELS, model), providers=["CPUExecutionProvider"])
    return s.run(None, {s.get_inputs()[0].name: x})[0]


def main():
    os.makedirs(OUT, exist_ok=True)
    page = Image.open(os.path.join(DATA, "z09_p1_150dpi.png"))
    W, H = page.size
    # the detector: the top third of the page (title and first paragraphs), 256x192
    det_in = tensor(page.crop((0, 0, W, H // 3)), 256, 192, True)
    det_out = run("PP-OCRv6_det_small.onnx", det_in)
    write(os.path.join(OUT, "det_in.bin"), det_in)
    write(os.path.join(OUT, "det_exp.bin"), det_out)
    print("det", det_in.shape, "->", det_out.shape, "max", float(det_out.max()))
    # the recogniser: a rendered text line (a page crop would need the layout's coordinates; a drawn line
    # is deterministic and legible), height 48, width 128 (16 CTC steps)
    from PIL import ImageDraw, ImageFont
    strip = Image.new("RGB", (640, 96), "white")
    ImageDraw.Draw(strip).text((16, 12), "Plaine 2026", fill="black", font=ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 60))
    strip = strip.crop((0, 0, 400, 96))
    rec_in = tensor(strip, 128, 48, False)
    rec_out = run("PP-OCRv6_rec_small.onnx", rec_in)
    write(os.path.join(OUT, "rec_in.bin"), rec_in)
    write(os.path.join(OUT, "rec_exp.bin"), rec_out)
    print("rec", rec_in.shape, "->", rec_out.shape, "argmax", rec_out[0].argmax(-1).tolist())
    # the classifier: the same strip at 48x192
    cls_in = tensor(strip, 192, 48, False)
    cls_out = run("ch_ppocr_mobile_v2.0_cls_mobile.onnx", cls_in)
    write(os.path.join(OUT, "cls_in.bin"), cls_in)
    write(os.path.join(OUT, "cls_exp.bin"), cls_out)
    print("cls", cls_in.shape, "->", cls_out.shape, cls_out.tolist())
    for f in sorted(os.listdir(OUT)):
        print("  ", f, os.path.getsize(os.path.join(OUT, f)), "bytes")


if __name__ == "__main__":
    main()
